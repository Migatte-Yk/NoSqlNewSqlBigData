-- =====================================================================
-- 02_esquema.sql  (A2. Diseño del esquema)
-- Crea la base dedicada practica_matriculas y sus 3 tablas.
-- Re-ejecutable: solo elimina/recrea las tablas DEL PROYECTO (DROP ... IF EXISTS),
-- en orden hijas -> padres. No toca otras bases de datos.
-- =====================================================================
CREATE DATABASE IF NOT EXISTS practica_matriculas;
USE practica_matriculas;

DROP TABLE IF EXISTS matriculas;
DROP TABLE IF EXISTS estudiantes;
DROP TABLE IF EXISTS programas;

-- Programas académicos (entidad padre)
CREATE TABLE programas (
    programa_id        INT8 PRIMARY KEY,
    codigo             STRING(8)  NOT NULL UNIQUE,
    nombre             STRING     NOT NULL,
    facultad           STRING     NOT NULL,
    duracion_semestres INT2       NOT NULL CHECK (duracion_semestres BETWEEN 1 AND 14)
);

-- Estudiantes (pertenecen a un programa). telefono es opcional (NULL permitido).
CREATE TABLE estudiantes (
    codigo           STRING(10) PRIMARY KEY,
    nombres          STRING     NOT NULL,
    apellidos        STRING     NOT NULL,
    correo           STRING     NOT NULL UNIQUE,
    fecha_nacimiento DATE       NOT NULL,
    ciudad           STRING     NOT NULL,
    programa_id      INT8       NOT NULL REFERENCES programas (programa_id),
    fecha_ingreso    DATE       NOT NULL,
    telefono         STRING(15) NULL,
    CONSTRAINT ck_correo CHECK (correo LIKE '%@%'),
    INDEX idx_estudiantes_programa (programa_id)
);

-- Matrículas (un estudiante puede tener varias, una por semestre)
CREATE TABLE matriculas (
    matricula_id      INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    codigo_estudiante STRING(10) NOT NULL REFERENCES estudiantes (codigo),
    semestre          STRING(6)  NOT NULL CHECK (semestre ~ '^[0-9]{4}-[12]$'),
    fecha_matricula   DATE       NOT NULL,
    estado            STRING     NOT NULL CHECK (estado IN ('ACTIVA','FINALIZADA','CANCELADA','APLAZADA')),
    creditos          INT2       NOT NULL CHECK (creditos BETWEEN 1 AND 24),
    valor             DECIMAL(12,2) NOT NULL CHECK (valor >= 0),
    CONSTRAINT uq_est_semestre UNIQUE (codigo_estudiante, semestre)
);

-- Verificación del esquema creado
SHOW TABLES;
SHOW CREATE TABLE matriculas;
SHOW CONSTRAINTS FROM estudiantes;
